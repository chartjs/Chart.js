const {chromium} = require(process.env.PW);
const path = require('path');
const variants = require('./variants.js');
const [variant, n, datasets, bw, br, alpha] = process.argv.slice(2);
(async () => {
  const browser = await chromium.launch({args: ['--js-flags=--expose-gc']});
  const page = await browser.newPage({viewport: {width: 1700, height: 900}});
  await page.goto('file://' + path.join(__dirname, 'page.html'));
  await page.evaluate(c => setup(c), {n: +n, datasets: +datasets, borderWidth: +bw, borderRadius: +br, alpha: alpha === '1'});
  if (variants[variant]) await page.evaluate(variants[variant]);
  const cdp = await page.context().newCDPSession(page);
  const r = await page.evaluate(() => bench(60));
  await page.evaluate(() => gc());
  await cdp.send('HeapProfiler.enable');
  await cdp.send('HeapProfiler.startSampling', {samplingInterval: 256, includeObjectsCollectedByMinorGC: true, includeObjectsCollectedByMajorGC: true});
  await page.evaluate(() => { const ctrls = chart.getSortedVisibleDatasetMetas().map(m => m.controller); for (let i = 0; i < 10; i++) for (const c of ctrls) c.draw(); });
  const {profile} = await cdp.send('HeapProfiler.stopSampling');
  let bytes = 0; const walk = nd => { for (const s of nd.selfSize ? [nd.selfSize] : []) bytes += s; nd.children.forEach(walk); }; walk(profile.head);
  const bars = n * datasets;
  console.log([variant, `bars=${bars}`, `bw=${bw}`, `br=${br}`, `alpha=${alpha}`, `median=${r.median.toFixed(2)}ms`, `p10=${r.p10.toFixed(2)}ms`, `us/bar=${(r.median*1000/bars).toFixed(2)}`, `alloc/bar/draw≈${Math.round(bytes/10/bars)}B`].join('\t'));
  await browser.close();
})();
